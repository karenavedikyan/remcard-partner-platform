/**
 * Основная точка партнёра — это сам партнёр (профиль/организация), а не запись Branch.
 * Филиалы — необязательные дополнительные адреса; для работы и публикации они не нужны.
 */
export function additionalAddressesSummary(count: number): string {
  return count > 0 ? `Доп. адреса: ${count}` : "Доп. адресов нет";
}
